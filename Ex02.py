# Objetivo: Ler dois números inteiros e mostrar a soma, a subtração e a multiplicação na mensagem.

# Pede dois números inteiros.
numero1 = int(input("Digite o primeiro número: "))
numero2 = int(input("Digite o segundo número: "))
# Formula para calcular a soma, subtração e a multiplicação dos números.
soma = numero1 + numero2
subtracao = numero1 - numero2
multiplicacao = numero1 * numero2
# Mostra o resultado da soma, subtração e da multiplicação.
print("Esse é o resultado da soma: ", soma)
print("Esse é o resultado da subtração: ", subtracao)
print("Esse é o resultado da multiplicação: ", multiplicacao)
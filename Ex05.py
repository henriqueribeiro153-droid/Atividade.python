# Objetivo:Ler a quantidade de minutos e mostrar quantas horas e minutas ela tem na mensagem.

# Pede a quantidade de minutos.
minutos = int(input("Digite a quantiade de minutos: "))

horas = minutos // 60
minutos_restantes = minutos % 60
print("Essas são as horas e minutos: ",horas,"horas", minutos_restantes,"minutos")





